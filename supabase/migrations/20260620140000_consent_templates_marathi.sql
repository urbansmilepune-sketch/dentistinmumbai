-- Multi-language consent templates: add a `language` flag (en / mr / both) and
-- a `template_group` that links the English + Marathi versions of the same
-- form so the UI can offer a language toggle when sending. Then seed Marathi
-- versions of the 6 single-language system templates (the basal_implant one
-- is already bilingual, so it's just flagged language = 'both').
--
-- Faithful reconstruction of the SQL run in the Supabase SQL editor (CLI not
-- linked to this project — migrations here are replayable records; see project
-- memory).

alter table public.consent_templates
  add column if not exists language text
    default 'en'
    check (language in ('en', 'mr', 'both')),
  add column if not exists template_group text;

-- Link existing system templates to their group (so English + Marathi pair up).
update public.consent_templates
set template_group = form_type, language = 'en'
where is_system = true and language is null;

-- The basal_implant template is already bilingual.
update public.consent_templates
set language = 'both', template_group = 'basal_implant'
where form_type = 'basal_implant' and is_system = true;

